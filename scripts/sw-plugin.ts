/**
 * Writes dist/sw.js at build time: a service worker that precaches every file of this build, so
 * the installed app (and the web version after one visit) plays offline. Each build gets its own
 * cache name, and the old one is dropped once the new worker takes over.
 */
import type { Plugin } from 'vite';

export function serviceWorker(version: string): Plugin {
  return {
    name: 'chess-rpg-tactics-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'sw.js');
      const precache = ['./', ...files.map((f) => `./${f}`), './manifest.webmanifest', './icons/icon-192.png', './icons/icon-512.png', './icons/maskable-512.png', './icons/apple-touch-icon.png'];
      const source = `/* Chess RPG Tactics ${version}: generated by scripts/sw-plugin.ts */
const CACHE = 'chess-rpg-tactics-${version}';
const PRECACHE = ${JSON.stringify([...new Set(precache)], null, 1)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('chess-rpg-tactics-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('message', (e) => {
  if (e.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Pages: the network first (new versions arrive at once), the cached page when offline
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./', { ignoreSearch: true, ignoreVary: true })));
    return;
  }
  // Everything else is fingerprinted or static: the cache first. ignoreVary, because module
  // scripts are fetched with CORS (an Origin header) and servers often answer with Vary: Origin
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    }
  };
}
